#!/bin/bash
# Run all STL test files through brepper and generate tests/RESULTS.md
# Usage: ./scripts/run_test_table.sh [<brepper_binary>]
# Default binary: ./target/release/brepper

set -euo pipefail
cd "$(dirname "$0")/.."

BREPPER="${1:-./target/release/brepper}"

if [ ! -x "$BREPPER" ]; then
    echo "Error: brepper binary not found at $BREPPER" >&2
    echo "Build with: cargo build --release" >&2
    exit 1
fi

OUTPUT="tests/RESULTS.md"

# Map STL file to its corresponding STEP file
find_step() {
    local stl="$1"
    local dir=$(dirname "$stl")
    local base=$(basename "$stl" .stl)

    # Strip .ascii suffix if present
    base="${base%.ascii}"

    # Try exact match first
    if [ -f "$dir/$base.step" ]; then
        echo "$dir/$base.step"
        return
    fi

    # Strip resolution suffixes (_coarse, _medium, _fine, _low, _high)
    local stripped=$(echo "$base" | sed -E 's/_(coarse|medium|fine|low|high)$//')
    if [ -f "$dir/$stripped.step" ]; then
        echo "$dir/$stripped.step"
        return
    fi

    echo ""
}

# Special flags for specific tests
get_extra_flags() {
    local stl="$1"
    case "$stl" in
        *rounded_cube_10_r2_coarse*)
            echo "--angular-tolerance 20"
            ;;
        *)
            echo ""
            ;;
    esac
}

# Count totals
total=0
pass_count=0
fail_count=0
bad_count=0

# Collect results into arrays for two-pass output
declare -a all_stls all_steps all_statuses all_times all_dirs

for stl in $(find tests -name '*.stl' | sort); do
    step=$(find_step "$stl")
    extra_flags=$(get_extra_flags "$stl")

    if [ -z "$step" ]; then
        compare_flag=""
    else
        compare_flag="--compare $step"
    fi

    tmpout=$(mktemp)
    # Write a real STEP file so stage 4.1's round-trip re-read and volume
    # comparison actually run (-o /dev/null cannot be re-read and fails).
    outstep="$tmpout.step"
    start_time=$(python3 -c 'import time; print(time.monotonic())')

    if timeout 120 "$BREPPER" "$stl" -o "$outstep" $compare_flag $extra_flags > "$tmpout" 2>&1; then
        status="✓"
        is_pass=1
    else
        exitcode=$?
        is_pass=0
        if [ $exitcode -eq 124 ]; then
            status="FAIL: timeout"
        else
            # Extract failure info from output
            last_line=$(tail -5 "$tmpout" | grep -iE "error|panic|fail|abort|thread" | tail -1 || true)
            if [ -n "$last_line" ]; then
                status="FAIL: $(echo "$last_line" | head -c 80)"
            else
                status="FAIL (exit $exitcode)"
            fi
        fi
    fi

    end_time=$(python3 -c 'import time; print(time.monotonic())')
    elapsed=$(python3 -c "print(f'{$end_time - $start_time:.2f}')")

    relpath="${stl#tests/}"
    stl_dir=$(dirname "$relpath")

    all_stls+=("$stl")
    all_steps+=("$step")
    all_statuses+=("$status")
    all_times+=("$elapsed")
    all_dirs+=("$stl_dir")

    total=$((total + 1))
    if [[ "$stl_dir" == "bad" ]]; then
        bad_count=$((bad_count + 1))
    elif [[ $is_pass -eq 1 ]]; then
        pass_count=$((pass_count + 1))
    else
        fail_count=$((fail_count + 1))
    fi

    # Print progress to stderr
    echo "  $status ($elapsed s) $stl" >&2

    rm -f "$tmpout" "$outstep"
done

# Generate RESULTS.md
{
    cat <<'HEADER'
<!-- This file is generated by scripts/run_test_table.sh — do not edit manually.
     To regenerate: ./scripts/run_test_table.sh [path/to/brepper]
     Default binary: ./target/release/brepper -->

# Test Results

Each STL test file is run through brepper with `--compare` against
its corresponding STEP file (when available):

```
brepper <input.stl> -o <tmpfile>.step --compare <input.step>
```

Special flags:
- `rounded_cube_10_r2_coarse`: `--angular-tolerance 20`

Models in `nurbs/` target the planned DEVELOPMENT_PLAN §2.7 NURBS fallback
and are EXPECTED to fail until it lands (see tests/nurbs/README.md); they
are counted under "failing non-bad" below to keep the scoreboard honest.

HEADER

    echo "Tests last run: $(date +%Y-%m-%d)."
    echo ""

    # Group by directory
    current_dir=""
    for i in "${!all_stls[@]}"; do
        stl="${all_stls[$i]}"
        step="${all_steps[$i]}"
        status="${all_statuses[$i]}"
        elapsed="${all_times[$i]}"
        dir="${all_dirs[$i]}"

        if [[ "$dir" != "$current_dir" ]]; then
            if [[ -n "$current_dir" ]]; then
                echo ""
            fi
            echo "## ${dir}"
            echo ""
            echo "| Test File | Status | Time | Notes |"
            echo "|-----------|--------|------|-------|"
            current_dir="$dir"
        fi

        basename=$(basename "$stl")
        if [[ "$status" == "✓" ]]; then
            echo "| $basename | ✓ | ${elapsed}s | |"
        else
            # Extract notes from the status
            notes="${status#FAIL: }"
            if [[ "$notes" == "$status" ]]; then
                echo "| $basename | $status | ${elapsed}s | |"
            else
                echo "| $basename | FAIL | ${elapsed}s | $notes |"
            fi
        fi
    done

    echo ""
    echo "## Summary"
    echo ""
    echo "- **Total test files**: $total"
    echo "- **Passing**: $pass_count / $total"
    echo "- **Expected failures (bad/)**: $bad_count"
    echo "- **Failing non-bad tests**: $fail_count"

} > "$OUTPUT"

echo "" >&2
echo "Results written to $OUTPUT" >&2
echo "Total: $total, Passing: $pass_count, Bad: $bad_count, Failing: $fail_count" >&2
